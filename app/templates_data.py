"""Sample agreement templates.

Templates generate a PDF on demand and pre-fill agreement metadata, so a user
can create a realistic agreement without authoring a document first.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from .pdf import build_pdf


@dataclass
class Template:
    key: str
    name: str
    agreement_type: str
    description: str
    sections: list[tuple[str, str]] = field(default_factory=list)
    default_value: float = 0.0

    def build_pdf(self, *, client_name: str, effective_date: str = "") -> bytes:
        title = f"{self.name}"
        if client_name:
            title = f"{self.name} - {client_name}"
        sections = list(self.sections)
        if effective_date:
            sections.insert(
                0, ("Effective Date", f"This agreement is effective as of {effective_date}.")
            )
        return build_pdf(
            title,
            sections,
            footer="Generated by Agreement Manager. Anchor string /sn1/ marks the signature line.",
        )


